"""Compiles the GE shaders to SPIR-V and embeds them in ge_shaders_spv.inc.

The SPIR-V is generated here, once, and committed: the builds (and the CI,
which has no Vulkan SDK) only compile the generated C++ file. The pipelines
specialise the shaders at run time with specialization constants (see
docs/sessions/F14a.md, "Decisiones").

Usage:
  python3 -I compile_shaders.py            # regenerate ge_shaders_spv.inc
  python3 -I compile_shaders.py --check    # fail if the .inc is stale

--check compares the SHA-256 of each source recorded in the .inc with the
current file. When glslangValidator is installed and has the version recorded
in the .inc, it also recompiles and compares the SPIR-V word by word.
"""

import argparse
import hashlib
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

SHADERS = (
    ('ge.vert', 'kGeVertSpv'),
    ('ge.frag', 'kGeFragSpv'),
)
TARGET_ENV = 'vulkan1.2'
OUTPUT = 'ge_shaders_spv.inc'
WORDS_PER_LINE = 8


def source_hash(path):
  """Returns the SHA-256 (hex) of a shader source."""
  return hashlib.sha256(path.read_bytes()).hexdigest()


def glslang_version(tool):
  """Returns glslangValidator's version line, e.g. 'Glslang Version: 11:15.1.0'."""
  out = subprocess.run([tool, '--version'], check=True, capture_output=True, text=True)
  return out.stdout.splitlines()[0].strip()


def compile_spirv(tool, source):
  """Compiles one shader and returns its SPIR-V as a list of 32-bit words."""
  with tempfile.TemporaryDirectory() as tmp:
    out = pathlib.Path(tmp) / 'out.spv'
    subprocess.run(
        [tool, '-V', '--target-env', TARGET_ENV, '-o', str(out), str(source)],
        check=True, capture_output=True, text=True)
    data = out.read_bytes()
  if len(data) % 4 != 0 or len(data) < 20:
    raise ValueError(f'{source}: invalid SPIR-V size {len(data)}')
  return [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]


def render(sources, version, spirv):
  """Returns the text of the generated .inc file."""
  lines = [
      '// SPDX-License-Identifier: GPL-3.0-or-later',
      '// Generated by compile_shaders.py (target env %s). Do not edit.' % TARGET_ENV,
      '// glslang: %s' % version,
  ]
  for name, _ in SHADERS:
    lines.append('// source-sha256 %s %s' % (name, source_hash(sources / name)))
  lines.append('// clang-format off')
  for name, symbol in SHADERS:
    words = spirv[name]
    lines.append('')
    lines.append('// %s: %d words.' % (name, len(words)))
    lines.append('inline constexpr std::uint32_t %s[] = {' % symbol)
    for i in range(0, len(words), WORDS_PER_LINE):
      chunk = words[i:i + WORDS_PER_LINE]
      lines.append('    ' + ', '.join('0x%08x' % w for w in chunk) + ',')
    lines.append('};')
  lines.append('// clang-format on')
  return '\n'.join(lines) + '\n'


def parse_inc(text):
  """Returns (recorded glslang version, {source: sha256}, {symbol: words})."""
  version_match = re.search(r'^// glslang: (.*)$', text, re.MULTILINE)
  hashes = dict(re.findall(r'^// source-sha256 (\S+) ([0-9a-f]{64})$', text, re.MULTILINE))
  arrays = {}
  for symbol, body in re.findall(
      r'std::uint32_t (\w+)\[\] = \{(.*?)\};', text, re.DOTALL):
    arrays[symbol] = [int(w, 16) for w in re.findall(r'0x([0-9a-f]{8})', body)]
  return (version_match.group(1) if version_match else None), hashes, arrays


def check(sources, tool):
  """Returns a list of problems with the committed .inc (empty when fresh)."""
  inc = sources / OUTPUT
  if not inc.exists():
    return [f'{inc} does not exist']
  version, hashes, arrays = parse_inc(inc.read_text())
  problems = []
  for name, symbol in SHADERS:
    current = source_hash(sources / name)
    if hashes.get(name) != current:
      problems.append(f'{name} changed since {OUTPUT} was generated: run compile_shaders.py')
    words = arrays.get(symbol, [])
    if not words or words[0] != 0x07230203:
      problems.append(f'{symbol}: missing or without the SPIR-V magic number')
  if tool and not problems:
    have = glslang_version(tool)
    if have == version:
      for name, symbol in SHADERS:
        if compile_spirv(tool, sources / name) != arrays.get(symbol):
          problems.append(f'{name}: recompiling with {have} gives different SPIR-V')
    else:
      print(f'note: {tool} is "{have}", the .inc was made with "{version}"; '
            'only the source hashes were checked')
  return problems


def main():
  parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
  parser.add_argument('--check', action='store_true', help='only check that the .inc is fresh')
  parser.add_argument('--glslang', default=shutil.which('glslangValidator'),
                      help='glslangValidator executable (default: from PATH)')
  args = parser.parse_args()
  sources = pathlib.Path(__file__).resolve().parent

  if args.check:
    problems = check(sources, args.glslang)
    for problem in problems:
      print('error: ' + problem, file=sys.stderr)
    if not problems:
      print(f'{OUTPUT} is up to date')
    return 1 if problems else 0

  if not args.glslang:
    print('error: glslangValidator not found (install glslang-tools)', file=sys.stderr)
    return 2
  spirv = {name: compile_spirv(args.glslang, sources / name) for name, _ in SHADERS}
  text = render(sources, glslang_version(args.glslang), spirv)
  (sources / OUTPUT).write_text(text)
  print(f'wrote {sources / OUTPUT}')
  return 0


if __name__ == '__main__':
  sys.exit(main())
