// mpo_vfpu_golden_gen: computes the golden vectors with PPSSPP's own
// interpreter and VFPU math (test-only build, never linked into the runtime).
//
//   mpo_vfpu_golden_gen --tables DIR --out FILE    write a new golden file
//   mpo_vfpu_golden_gen --tables DIR --check FILE  regenerate and compare
//   mpo_vfpu_golden_gen --tables DIR --exhaustive NAME [--threads N]
//       compares PPSSPP and mpo_vfpu on all 2^32 inputs of a one-argument
//       math function (local evidence; takes minutes in a release build)
//
// Exit codes: 0 ok, 1 the checked file differs, 2 error.

#include <atomic>
#include <bit>
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <string>
#include <thread>
#include <vector>

#include "golden/golden.hpp"
#include "ppsspp_ref/ppsspp_ref.hpp"
#include "vfpu/vfpu.hpp"

namespace {

const char *const kHeader =
    "# SPDX-License-Identifier: GPL-3.0-or-later\n"
    "#\n"
    "# Golden vectors for mpo_vfpu, generated by mpo_vfpu_golden_gen with PPSSPP\n"
    "# v1.20.4's own interpreter and VFPU math, built only into this test-only\n"
    "# generator (see profiles/mpo/tests/golden/golden.hpp for the format).\n"
    "# Regenerate with: mpo_vfpu_golden_gen --tables <MPO_VFPU_TABLES_DIR> --out <this file>\n"
    "#\n"
    "# kind name seed count digest\n";

// Every 32-bit input of a one-argument function, split across threads.
int exhaustive(const mpo::golden::FunctionInfo &info, int threads) {
    std::atomic<std::uint64_t> mismatches{0};
    std::atomic<std::uint32_t> first_bad{0};
    std::vector<std::thread> workers;
    const std::uint64_t total = 0x100000000ull;
    for (int t = 0; t < threads; ++t) {
        workers.emplace_back([&, t] {
            const std::uint64_t begin =
                total * static_cast<std::uint64_t>(t) / static_cast<std::uint64_t>(threads);
            const std::uint64_t end =
                total * static_cast<std::uint64_t>(t + 1) / static_cast<std::uint64_t>(threads);
            std::uint64_t local = 0;
            for (std::uint64_t bits = begin; bits < end; ++bits) {
                const float x = std::bit_cast<float>(static_cast<std::uint32_t>(bits));
                const float a = mpo::ppsspp_ref::call(info.fn, &x);
                const float b = mpo::golden::call_mpo(info.fn, &x);
                if (std::bit_cast<std::uint32_t>(a) != std::bit_cast<std::uint32_t>(b)) {
                    if (local++ == 0) first_bad = static_cast<std::uint32_t>(bits);
                }
            }
            mismatches += local;
        });
    }
    for (std::thread &worker : workers) worker.join();
    std::printf("%s: 4294967296 inputs, %llu mismatched", info.name,
                static_cast<unsigned long long>(mismatches.load()));
    if (mismatches.load() != 0) std::printf(" (e.g. input %08x)", first_bad.load());
    std::printf("\n");
    return mismatches.load() == 0 ? 0 : 1;
}

} // namespace

int main(int argc, char **argv) {
    std::string tables;
    std::string out_path;
    std::string check_path;
    std::string exhaustive_name;
    int threads = 4;
    for (int i = 1; i + 1 < argc; i += 2) {
        const std::string arg = argv[i];
        if (arg == "--tables") {
            tables = argv[i + 1];
        } else if (arg == "--out") {
            out_path = argv[i + 1];
        } else if (arg == "--check") {
            check_path = argv[i + 1];
        } else if (arg == "--exhaustive") {
            exhaustive_name = argv[i + 1];
        } else if (arg == "--threads") {
            threads = std::atoi(argv[i + 1]);
        } else {
            std::fprintf(stderr, "unknown argument %s\n", arg.c_str());
            return 2;
        }
    }
    std::string error;
    if (tables.empty() || !mpo::ppsspp_ref::init(tables, &error)) {
        std::fprintf(stderr, "mpo_vfpu_golden_gen: %s\n",
                     error.empty() ? "--tables is required" : error.c_str());
        return 2;
    }

    if (!exhaustive_name.empty()) {
        if (!mpo::vfpu::load_tables(tables, &error)) {
            std::fprintf(stderr, "mpo_vfpu_golden_gen: %s\n", error.c_str());
            return 2;
        }
        for (const mpo::golden::FunctionInfo &info : mpo::golden::all_functions()) {
            if (info.name == exhaustive_name && info.arity == 1) return exhaustive(info, threads);
        }
        std::fprintf(stderr, "unknown one-argument function %s\n", exhaustive_name.c_str());
        return 2;
    }

    // pin lines come from mpo_vfpu itself (see golden.hpp).
    if (!mpo::vfpu::load_tables(tables, &error)) {
        std::fprintf(stderr, "mpo_vfpu_golden_gen: %s\n", error.c_str());
        return 2;
    }
    auto executor = mpo::ppsspp_ref::make_executor();
    auto mpo_executor = mpo::difftest::make_reference_interpreter();
    std::vector<mpo::golden::Entry> entries = mpo::golden::plan();
    for (mpo::golden::Entry &entry : entries) {
        if (entry.kind == "op" || entry.kind == "pin") {
            mpo::difftest::Executor &which = entry.kind == "op" ? *executor : *mpo_executor;
            if (!mpo::golden::digest_op(entry, which, &entry.digest, &error)) {
                std::fprintf(stderr, "mpo_vfpu_golden_gen: %s\n", error.c_str());
                return 2;
            }
        } else {
            for (const mpo::golden::FunctionInfo &info : mpo::golden::all_functions()) {
                if (entry.name != info.name) continue;
                const std::vector<float> inputs =
                    mpo::golden::make_inputs(info, entry.seed, entry.count);
                entry.digest = mpo::golden::digest_function(info, inputs, mpo::ppsspp_ref::call);
            }
        }
    }

    if (!out_path.empty()) {
        std::ofstream out(out_path);
        out << kHeader;
        for (const mpo::golden::Entry &entry : entries) out << mpo::golden::format(entry) << '\n';
        if (!out) {
            std::fprintf(stderr, "mpo_vfpu_golden_gen: cannot write %s\n", out_path.c_str());
            return 2;
        }
        std::printf("wrote %zu entries to %s\n", entries.size(), out_path.c_str());
    }

    if (!check_path.empty()) {
        std::ifstream in(check_path);
        std::vector<mpo::golden::Entry> stored;
        std::string line;
        while (std::getline(in, line)) {
            mpo::golden::Entry entry;
            if (line.empty() || line[0] == '#') continue;
            if (!mpo::golden::parse(line, &entry)) {
                std::fprintf(stderr, "malformed line: %s\n", line.c_str());
                return 2;
            }
            stored.push_back(entry);
        }
        int differences = 0;
        if (stored.size() != entries.size()) {
            std::printf("entry count differs: file %zu, regenerated %zu\n", stored.size(),
                        entries.size());
            ++differences;
        }
        for (std::size_t i = 0; i < stored.size() && i < entries.size(); ++i) {
            const std::string a = mpo::golden::format(stored[i]);
            const std::string b = mpo::golden::format(entries[i]);
            if (a != b) {
                std::printf("file:        %s\nregenerated: %s\n", a.c_str(), b.c_str());
                ++differences;
            }
        }
        std::printf("%zu entries checked against PPSSPP, %d differ\n", entries.size(), differences);
        return differences == 0 ? 0 : 1;
    }
    return 0;
}
